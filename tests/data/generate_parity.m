% Run this in GNU Octave (or MATLAB) inside the
% superposed-folds-reference/ directory after copying it there.
%
% Generates parity_<id>.npz-equivalent .mat files containing X, Y, Z_final,
% Z_initial for each named preset. Then convert to .npz with the helper
% Python script in tests/data/mat_to_npz.py.

addpath('.');

% Common grid (small, for fast tests)
np = 32;
L  = 5*pi;
[X, Y] = meshgrid(linspace(-L/2, L/2, np), linspace(-L/2, L/2, np));
Z = zeros(size(X));

% A few representative presets
presets = struct( ...
  'type_0_3', struct('dipdirA1', 0, 'dipA1', 90, 'rake1', 0, ...
                     'A1', 3, 'B1', 1, 'C1', 1, ...
                     'dipdirA2', 0, 'dipA2', 90, 'rake2', 0, ...
                     'A2', 3, 'B2', 1, 'C2', 1), ...
  'type_1',   struct('dipdirA1', 0, 'dipA1', 90, 'rake1', 0, ...
                     'A1', 3, 'B1', 1, 'C1', 1, ...
                     'dipdirA2', 90, 'dipA2', 90, 'rake2', 0, ...
                     'A2', 3, 'B2', 1, 'C2', 1), ...
  'type_2',   struct('dipdirA1', 0, 'dipA1', 90, 'rake1', 0, ...
                     'A1', 3, 'B1', 1, 'C1', 1, ...
                     'dipdirA2', 90, 'dipA2', 90, 'rake2', 90, ...
                     'A2', 3, 'B2', 1, 'C2', 1), ...
  'type_3',   struct('dipdirA1', 0, 'dipA1', 90, 'rake1', 0, ...
                     'A1', 3, 'B1', 1, 'C1', 1, ...
                     'dipdirA2', 0, 'dipA2', 0, 'rake2', 0, ...
                     'A2', 3, 'B2', 1, 'C2', 1));

names = fieldnames(presets);
for i = 1:numel(names)
  n = names{i};
  p = presets.(n);
  Zini = fold_interference_pattern(X, Y, Z, ...
    p.dipdirA1, p.dipA1, p.rake1, p.A1, p.B1, p.C1, ...
    p.dipdirA2, p.dipA2, p.rake2, p.A2, p.B2, p.C2);
  save('-v7', sprintf('parity_%s.mat', n), 'X', 'Y', 'Z', 'Zini');
end

disp('Done. Run tests/data/mat_to_npz.py next.');
